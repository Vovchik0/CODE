"""
mc_load_tester
==============

Модульное приложение для нагрузочного тестирования собственного
Minecraft-сервера с графическим интерфейсом на Qt (PyQt5 или PyQt4).

Модули:
    config    -- поддерживаемые версии, протоколы и структура конфигурации
    logger    -- настройка журналирования (файл + сигнал для GUI)
    protocol  -- реализация клиентской части протокола Minecraft (handshake/login)
    status    -- Server List Ping (MOTD, онлайн, версия, задержка)
    engine    -- Qt-независимое ядро теста (потоки, статистика, ramp-up)
    updater   -- самообновление через git (для веб-сервера и скриптов)
    qtcompat  -- слой совместимости биндингов Qt (PyQt5 -> PyQt4)
    tester    -- Qt-обёртка (QThread) над движком для десктопного GUI
    gui       -- графический интерфейс (тёмная тема, поля ввода, журнал, статистика)

Веб-версия (управление с телефона/браузера) реализована в модуле верхнего
уровня ``web_server`` и переиспользует тот же :mod:`engine`.

Приложение предназначено ИСКЛЮЧИТЕЛЬНО для проверки производительности и
совместимости серверов, которыми владеет или которые администрирует
пользователь.
"""

